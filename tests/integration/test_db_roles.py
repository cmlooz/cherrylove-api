"""Least-privilege database roles: DDL only as maintenance, DML only as app (ADR-008 §4, DATA-001 §3)."""

from __future__ import annotations

import uuid
from collections.abc import Iterator

import pytest
from django.db import ProgrammingError, connections, transaction

pytestmark = pytest.mark.integration


def _scalar(alias: str, sql: str, params: tuple[str, ...] = ()) -> object:
    with connections[alias].cursor() as cursor:
        cursor.execute(sql, params)
        row = cursor.fetchone()
    assert row is not None
    return row[0]


@pytest.fixture
def probe_table() -> Iterator[str]:
    """A table created the way migrations create tables: by the maintenance role, committed."""
    name = f"probe_{uuid.uuid4().hex[:8]}"
    with connections["maintenance"].cursor() as cursor:
        cursor.execute(f"CREATE TABLE {name} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text)")
    yield name
    with connections["maintenance"].cursor() as cursor:
        cursor.execute(f"DROP TABLE {name}")


@pytest.mark.req("REQ-F-LOG-03")
@pytest.mark.django_db(databases=["default", "maintenance"])
def test_migrations_run_as_the_maintenance_role() -> None:
    assert _scalar("maintenance", "SELECT current_user") == "cherrylove_maintenance"
    assert _scalar("default", "SELECT current_user") == "cherrylove_app"
    owner = _scalar("maintenance", "SELECT tableowner FROM pg_tables WHERE tablename = 'django_migrations'")
    assert owner == "cherrylove_maintenance"
    applied = _scalar(
        "default",
        "SELECT count(*) FROM django_migrations WHERE app = %s AND name = %s",
        ("shared", "0001_app_role_default_privileges"),
    )
    assert applied == 1


@pytest.mark.req("REQ-F-LOG-03")
@pytest.mark.django_db(databases=["default", "maintenance"], transaction=True)
def test_app_role_gets_dml_through_default_privileges(probe_table: str) -> None:
    with connections["default"].cursor() as cursor:
        cursor.execute(f"INSERT INTO {probe_table} (note) VALUES ('a') RETURNING id")
        row = cursor.fetchone()
        assert row is not None
        cursor.execute(f"UPDATE {probe_table} SET note = 'b' WHERE id = %s", (row[0],))
        cursor.execute(f"SELECT note FROM {probe_table} WHERE id = %s", (row[0],))
        assert cursor.fetchone() == ("b",)
        cursor.execute(f"DELETE FROM {probe_table} WHERE id = %s", (row[0],))
        assert cursor.rowcount == 1


@pytest.mark.req("REQ-F-LOG-03")
@pytest.mark.django_db(databases=["default", "maintenance"])
@pytest.mark.parametrize(
    "ddl",
    [
        "CREATE TABLE app_owned (id int)",
        "ALTER TABLE django_migrations ADD COLUMN x int",
        "DROP TABLE django_migrations",
    ],
)
def test_app_role_is_denied_ddl(ddl: str) -> None:
    with (
        pytest.raises(ProgrammingError, match=r"permission denied|must be owner"),
        transaction.atomic(using="default"),
        connections["default"].cursor() as cursor,
    ):
        cursor.execute(ddl)
